package org.eclipse.edc.api.authorization.filter;

import jakarta.ws.rs.container.DynamicFeature;
import jakarta.ws.rs.container.ResourceInfo;
import jakarta.ws.rs.core.FeatureContext;
import org.eclipse.edc.api.auth.spi.RequiredScope;
import org.eclipse.edc.spi.monitor.Monitor;

/**
 * Registers a {@link ScopeBasedAccessFilter} on the resource methods annotated with {@link RequiredScope}. The access to
 * a resource method that is not annotated is denied, except for the OPTIONS handlers generated by Jersey.
 */
public class ScopeBasedAccessFeature implements DynamicFeature {

    private final Monitor monitor;

    public ScopeBasedAccessFeature(Monitor monitor) {
        this.monitor = monitor;
    }

    private static final String JERSEY_PACKAGE = "org.glassfish.jersey.";

    @Override
    public void configure(ResourceInfo resourceInfo, FeatureContext featureContext) {
        if (resourceInfo.getResourceClass().getName().startsWith(JERSEY_PACKAGE)) {
            // the OPTIONS handlers that Jersey generates for every resource: OPTIONS requests are not authenticated
            // either, so that CORS preflight requests succeed
            return;
        }
        var method = resourceInfo.getResourceMethod();
        var annotation = method.getAnnotation(RequiredScope.class);
        if (annotation != null) {
            featureContext.register(new ScopeBasedAccessFilter(annotation.value()));
        } else {
            monitor.warning("Method %s.%s has no @%s: access to it is denied".formatted(
                    resourceInfo.getResourceClass().getName(), method.getName(), RequiredScope.class.getSimpleName()));
            featureContext.register(new DenyAccessFilter());
        }
    }
}
